"""Render every measured result into one markdown document, ready to paste into the
paper.

Insurance, written because the campaign's results live on /scratch, which is purged
and not backed up, and because a re-run may not finish before the deadline: whatever
is already measured has to be quotable without re-deriving it from CSVs.

Reads the per-cell *_bench.csv files the timing harness writes and the summary.md the
fidelity validation writes, and emits tables plus the provenance each number needs --
which population, which engine build, how many seeds.

    python scripts/make_results_archive.py --bench-dir DIR --label berlin ... \\
        --notes docs/results_notes.md --output RESULTS.md

`scripts/regenerate_results.sh` holds the exact invocation that produced the committed
RESULTS.md, against the CSVs under `results/`.
"""

from __future__ import annotations

import argparse
import csv
import glob
import os
import statistics as st
from collections import defaultdict

ENGINES = ("matsim", "sumo", "torchdnl_gpu", "torchdnl_cpu")
PRETTY = {"matsim": "MATSim", "sumo": "SUMO (meso)",
          "torchdnl_gpu": "TorchDNL H100", "torchdnl_cpu": "TorchDNL CPU"}


def series_key(row: dict) -> str:
    """Which curve a row belongs to; the CSV says `torchdnl` for both devices."""
    if row["engine"] == "torchdnl":
        return "torchdnl_cpu" if "_torchdnl_cpu_" in row["tag"] else "torchdnl_gpu"
    return row["engine"]


def load(bench_dir: str) -> tuple[dict, dict, dict]:
    rows = []
    for f in glob.glob(f"{bench_dir}/*_bench.csv"):
        rows += list(csv.DictReader(open(f)))
    t, n, arr = defaultdict(list), {}, defaultdict(list)
    for r in rows:
        load_v = float(r["loading"])
        v = r.get("t_engine_s")
        if v and str(v).lower() != "nan":
            t[(load_v, series_key(r))].append(float(v))
        if r.get("n_agents"):
            n[load_v] = int(float(r["n_agents"]))
        if r.get("arrived") and r.get("n_agents"):
            arr[load_v].append(float(r["arrived"]) / float(r["n_agents"]))
    return t, n, arr


def table(bench_dir: str, title: str, out) -> None:
    t, n, arr = load(bench_dir)
    if not n:
        out.append(f"\n### {title}\n\n_No data._\n")
        return
    out.append(f"\n### {title}\n")
    out.append("| Loading | Travellers | Arrived % | "
               + " | ".join(PRETTY[e] for e in ENGINES)
               + " | MATSim/GPU | SUMO/GPU |")
    out.append("|---" * (5 + len(ENGINES)) + "|")
    for L in sorted(n):
        a = 100 * st.mean(arr[L]) if arr.get(L) else float("nan")
        cells = []
        for e in ENGINES:
            v = t.get((L, e))
            cells.append(f"{st.mean(v):,.0f} s (n={len(v)})" if v else "—")
        g = t.get((L, "torchdnl_gpu"))
        ratios = []
        for e in ("matsim", "sumo"):
            v = t.get((L, e))
            ratios.append(f"{st.mean(v) / st.mean(g):.2f}×" if v and g else "—")
        out.append(f"| {L:g} | {n[L]:,} | {a:.1f} | " + " | ".join(cells)
                   + " | " + " | ".join(ratios) + " |")


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--bench", action="append", default=[],
                   help="label=dir, repeatable.")
    p.add_argument("--fidelity", action="append", default=[],
                   help="label=path/to/summary.md, repeatable.")
    p.add_argument("--notes", default=None,
                   help="Markdown file appended verbatim after the tables (provenance, "
                        "caveats, anything a reader needs to read the numbers correctly).")
    p.add_argument("--output", required=True)
    args = p.parse_args()

    out: list[str] = []
    out.append("# TrafficGym — measured results\n")
    out.append("Generated by `scripts/make_results_archive.py`. Every number here is "
               "measured, none extrapolated.\n")

    if args.bench:
        out.append("\n## Wall-clock scaling\n")
        out.append("`t_engine_s` only: the engine's own loop, excluding scenario "
                   "parsing and setup. Every engine on the same node type with the "
                   "same CPU allocation, 36 h horizon, capacity scaled with the "
                   "population. Three seeds per cell unless stated.\n")
        for spec in args.bench:
            label, d = spec.split("=", 1)
            table(d, label, out)

    if args.fidelity:
        out.append("\n## DNL fidelity against MATSim\n")
        for spec in args.fidelity:
            label, path = spec.split("=", 1)
            out.append(f"\n### {label}\n")
            if not os.path.exists(path):
                out.append("_Missing._\n")
                continue
            body = open(path).read().strip()
            # Drop the generated title; this document supplies its own heading.
            out.append("\n".join(l for l in body.splitlines()
                                 if not l.startswith("# ")))

    if args.notes:
        out.append("\n" + open(args.notes).read().rstrip())

    with open(args.output, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"wrote {args.output} ({len(out)} blocks)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
